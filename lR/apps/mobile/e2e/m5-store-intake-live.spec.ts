import {test,expect} from '@playwright/test';
import {randomUUID} from 'node:crypto';
/** Real Chromium -> Expo Web -> isolated Express/MySQL -> receipt, without charging. */
test('signed-in STORE checkout saves an unpaid order, then owner history reads it back',async({page})=>{
 test.skip(process.env.M4N_MODE!=='experience-live','isolated test API required');
 const email='store-'+randomUUID().slice(0,13)+'@example.invalid';
 const password='synthetic-store-account-password-2026';
 await page.goto('/my/login');
 await page.getByRole('button',{name:'테스트 계정 새로 만들기'}).click();
 await page.getByRole('textbox',{name:'테스트 이메일'}).fill(email);
 await page.getByRole('textbox',{name:'테스트 비밀번호'}).fill(password);
 await page.getByRole('button',{name:'테스트 계정 생성하기'}).click();
 await expect(page.getByText(/시연 계정을 생성했습니다/)).toBeVisible();
 await page.getByRole('textbox',{name:'테스트 비밀번호'}).fill(password);
 await page.getByRole('button',{name:'테스트 계정 로그인'}).click();
 await expect(page.getByText('테스트 계정: '+email)).toBeVisible();
 await expect(page.getByText('테스트 계정의 찜·장바구니를 불러오는 중입니다.')).toHaveCount(0);
 await page.getByText('스토어',{exact:true}).last().click();
 await expect(page.getByText('스토어 상품',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'The Sera Top Handle 상세 보기'}).click();
 const cartSaved=page.waitForResponse(r=>r.url().includes('/api/v1/me/cart')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'스토어 시연 장바구니에 담기'}).click();
 expect((await cartSaved).status()).toBe(201);
 await expect(page.getByText('구매 주문서',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:'간편결제'}).click();
 await page.getByRole('button',{name:'매장 방문 수령'}).click();
 await page.getByRole('button',{name:'접수 조건 확인'}).click();
 const accepted=page.waitForResponse(r=>r.url().includes('/api/v1/experience/store-orders')&&r.request().method()==='POST');
 await page.getByRole('button',{name:'스토어 주문 접수'}).click();
 expect((await accepted).status()).toBe(201);
 await expect(page.getByText('스토어 주문이 접수되었습니다',{exact:true})).toBeVisible();
 await expect(page.getByText('접수 상태: 접수 완료 · 결제 상태: 미결제')).toBeVisible();
 const label=await page.getByText(/^주문번호: /).textContent();
 const orderId=label?.replace('주문번호: ','').trim();
 expect(orderId).toMatch(/^[0-9a-f-]{36}$/);
 await page.getByRole('button',{name:'내 스토어 주문 내역 보기'}).click();
 await expect(page.getByText('접수된 스토어 주문',{exact:true})).toBeVisible();
 await page.getByRole('button',{name:/The Sera Top Handle/}).click();
 await expect(page.getByText('주문번호: '+orderId,{exact:true})).toBeVisible();
});
